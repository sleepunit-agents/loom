it('feeds two browser selections from one real GraphQL socket and clears them at access expiry',async()=>{
 const db=new Database(':memory:');clean.push(()=>{db.close();});createDataSchema(db);
 db.exec("INSERT INTO members(id,role,joined_at) VALUES('fiction','owner','2026-11-14T00:00:00Z'); INSERT INTO tasks(id,title,owner_kind,created_by_kind,created_by,created_at,changed_at) VALUES('fiction-task','Fictional pump','household','member','fiction','2026-11-14T00:00:00Z','2026-11-14T00:00:00Z')");
 const clock=new FakeClock(0),live=new DataLive();clean.push(()=>live.close());
 const socket=dataSocket({live,clock,authenticate:()=>({viewer:{kind:'member',id:'fiction'},valid:()=>clock.now()<1000,expiresAt:1000}),schema:viewer=>dataQueries(db,{tables:['tasks'],visibility:taskVisibility(viewer)}),originAllowed:()=>true});
 const server=createServer();socket.attach(server);await new Promise<void>(ok=>server.listen(0,'127.0.0.1',ok));
 clean.push(()=>new Promise<void>(ok=>server.close(()=>ok())));clean.push(()=>socket.close());
 const address=server.address();if(!address||typeof address==='string')throw Error();
 vi.stubGlobal('location',{protocol:'http:',host:`127.0.0.1:${address.port}`});
 let connections=0;const frames:string[]=[];
 class BrowserSocket extends WebSocket {constructor(url:string,protocols:string|string[]){super(url,protocols);connections++;this.on('message',raw=>frames.push(String(raw)));}}
 vi.stubGlobal('WebSocket',BrowserSocket);
 const store=new QueryStore(queryTransport);clean.push(()=>store.close());
 const list={query:'{ tasks { id title } }'},detail={query:'{ tasks { title } }'};
 const off=store.subscribe(list,()=>{});store.subscribe(detail,()=>{});
 await vi.waitFor(()=>expect({snapshot:store.getSnapshot(list),frames}).toMatchObject({snapshot:{status:'live'}}));
 await vi.waitFor(()=>expect(store.getSnapshot(detail).status).toBe('live'));
 expect(connections).toBe(1);expect(store.getSnapshot(list).data).toEqual({tasks:[{id:'fiction-task',title:'Fictional pump'}]});
 const before=store.getSnapshot(list);db.exec("UPDATE tasks SET title='Changed fictional pump'");live.changed();
 await vi.waitFor(()=>expect(store.getSnapshot(list).data).toEqual({tasks:[{id:'fiction-task',title:'Changed fictional pump'}]}));
 expect(before.data).toEqual({tasks:[{id:'fiction-task',title:'Fictional pump'}]});
 expect(frames.some(raw=>raw.includes('"path":["tasks",0,"title"]'))).toBe(true);
 off();expect(store.getSnapshot(list)).toEqual({status:'loading'});
 clock.advance(1000);await vi.waitFor(()=>expect(store.getSnapshot(detail)).toEqual({status:'denied'}));
 expect(connections).toBe(1);
},2000);
