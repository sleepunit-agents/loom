import {createElement as h} from 'react';
import {act,create,type ReactTestRenderer} from 'react-test-renderer';
import {afterEach,expect,it,vi} from 'vitest';
import type {DataQuerySnapshot} from '../../data/graphql';
const state=vi.hoisted(()=>({feed:{status:'loading'} as DataQuerySnapshot<{settledInboxNotice:{id:string;needs:number;fyi:number}|null}>}));
vi.mock('../../data/graphql',()=>({useDataQuery:()=>state.feed}));
vi.mock('../attention/registration',()=>({inboxApp:{path:'/registered-inbox'}}));
import InboxNotice from './notice';
let tree:ReactTestRenderer|undefined;afterEach(async()=>{await act(async()=>tree?.unmount());tree=undefined;vi.useRealTimers();});
it('shows only live settled metadata, uses the registered Inbox destination and dismisses one occurrence',async()=>{
 vi.useFakeTimers();
 state.feed={status:'live',data:{settledInboxNotice:null}};await act(async()=>{tree=create(h(InboxNotice));});expect(tree!.toJSON()).toBeNull();
 const update=async(feed:typeof state.feed)=>{state.feed=feed;await act(async()=>tree!.update(h(InboxNotice)));};
 await update({status:'live',data:{settledInboxNotice:{id:'one',needs:1,fyi:1}}});
 expect(JSON.stringify(tree!.toJSON())).toContain('1 needs your response · 1 FYI');expect(tree!.root.findByType('a').props.href).toBe('/registered-inbox');
 await act(async()=>tree!.root.findByType('button').props.onClick());await act(async()=>{vi.advanceTimersByTime(180); });expect(tree!.toJSON()).toBeNull();
 await update({status:'live',data:{settledInboxNotice:{id:'one',needs:0,fyi:1}}});expect(tree!.toJSON()).toBeNull();
 await update({status:'live',data:{settledInboxNotice:{id:'two',needs:0,fyi:1}}});expect(JSON.stringify(tree!.toJSON())).toContain('1 FYI');
 await act(async()=>{vi.advanceTimersByTime(8000); });expect(tree!.root.findByType('aside').props['data-closing']).toBe(true);
 await act(async()=>{vi.advanceTimersByTime(180); });expect(tree!.toJSON()).toBeNull();
 await update({status:'live',data:{settledInboxNotice:{id:'empty',needs:0,fyi:0}}});expect(tree!.toJSON()).toBeNull();
 await update({status:'offline',data:{settledInboxNotice:{id:'two',needs:0,fyi:1}}});expect(tree!.toJSON()).toBeNull();
 await update({status:'live',data:{settledInboxNotice:null}});expect(tree!.toJSON()).toBeNull();
});
