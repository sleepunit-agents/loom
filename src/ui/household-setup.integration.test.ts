import { generateX25519Identity } from 'age-encryption';
import { wordsKey } from '../pieces/comms/crypto.js';
/** One Household setup browser proof through the running shared program. */
import {it,expect} from 'vitest';
import Database from 'better-sqlite3';
import {createHash} from 'node:crypto';
import {existsSync,mkdirSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {chromium} from 'playwright-core';
import {FakeClock} from '../core/clock.js';
import {createDataSchema} from '../core/data/database.js';
import {members,agents,tokens,sessions,agentAccounts,household,memberAgents} from '../core/data/schema.js';
import {serveShared} from '../shared-serve.js';
import {deskMemoryFixture} from './desk-memory.fixture.js';
const enabled=process.env.LOOM_DESK_EVIDENCE==='1',chrome=process.env.LOOM_TEST_CHROME,webRoot=resolve('dist/web');
if(enabled&&(!chrome||!existsSync(chrome)||!existsSync(join(webRoot,'index.html'))))throw Error('Setup evidence needs Chrome and the built app');
it.runIf(enabled)('Household owners request roster changes, see automated token issuance refused and end another browser across shared windows',async()=>{
 const client=new Database(':memory:'),clock=new FakeClock(),now=()=>new Date(clock.now()).toISOString(),db=createDataSchema(client,now),hash=(value:string)=>createHash('sha256').update(value).digest('hex'),cookie='c'.repeat(64);
 db.insert(members).values([{id:'owner',role:'owner',joinedAt:now()},{id:'sam',role:'member',joinedAt:now()}]).run();db.insert(agents).values({id:'art',about:'Fixture agent',markBg:'#000000',markFg:'#ffffff',faceShape:'pebble',faceEyes:'dot'}).run();
 for(const [member,raw]of [['owner','a'.repeat(64)],['sam','b'.repeat(64)]])db.insert(tokens).values({fingerprint:hash(raw),kind:'owner',member,label:member,createdAt:now()}).run();
 db.insert(sessions).values([{id:hash(cookie),token:hash('a'.repeat(64)),device:'Current owner browser',via:'link',isAgent:false,issuedAt:now(),seenAt:now(),provedAt:now()},{id:hash('d'.repeat(64)),token:hash('b'.repeat(64)),device:'Kitchen tablet',via:'link',isAgent:false,issuedAt:now(),seenAt:now(),provedAt:now()}]).run();
 db.insert(household).values({singleton:1,defaultAgent:'art',timezone:'America/Chicago'}).run();
 db.insert(memberAgents).values({member:'owner',agent:'art'}).run();
 const memory=deskMemoryFixture(['art']),app=await serveShared({db,clock,webRoot,commsKey:wordsKey(await generateX25519Identity()),memory:{sources:memory.sources,checkingAgent:'art'},originAllowed:()=>true,reportError:error=>{throw error;}}),browser=await chromium.launch({executablePath:chrome,args:['--no-sandbox']});
 try{
  const context=await browser.newContext({serviceWorkers:'block',viewport:{width:1280,height:900}});const a=await context.newPage(),b=await context.newPage(),errors:string[]=[];let legacy=0;
  const login=await app.http.request(app.url+'/api/signin/link',{method:'POST',headers:{authorization:'Bearer '+'a'.repeat(64),'content-type':'application/json'},body:JSON.stringify({input:{}})});
  expect(login.status).toBe(200);
  await a.goto(app.url+(await login.json()).value.path);
  await a.getByRole('button',{name:'Sign in',exact:true}).click();
  for(const page of [a,b]){page.on('pageerror',error=>errors.push(error.message));page.on('websocket',socket=>{if(new URL(socket.url()).pathname==='/live')legacy++;});await page.goto(app.url+'/p/setup-preview');}
  await a.locator('.loom-desk-boot').waitFor({state:'hidden'});
  const add=a.getByRole('form',{name:'Add member',exact:true});
  await add.getByRole('checkbox',{name:'art',exact:true}).check();
  await add.getByRole('textbox',{name:'Member name'}).fill('pat');
  await add.getByRole('button',{name:'Request new member'}).click();
  const draft=a.getByRole('textbox',{name:'Message art',exact:true});
  expect(await draft.inputValue()).toContain('pat');
  expect(db.select().from(members).all().some(member=>member.id==='pat')).toBe(false);
  await a.getByRole('button',{name:'Close draft'}).click();
  const appearance=a.getByRole('form',{name:'Save appearance for art'});
  await appearance.getByRole('textbox',{name:'Description'}).fill('Updated fixture description');
  await appearance.getByRole('button',{name:'Request appearance change'}).click();
  expect(await draft.inputValue()).toContain('Updated fixture description');
  expect(db.select().from(agents).get()?.about).toBe('Fixture agent');
  await a.getByRole('button',{name:'Close draft'}).click();
  const accounts=a.getByRole('form',{name:'Save accounts for art'});
  await accounts.getByRole('textbox',{name:'GitHub accounts'}).fill('ART-BOT');
  await accounts.getByRole('button',{name:'Request account change'}).click();
  expect(await draft.inputValue()).toContain('ART-BOT');
  expect(db.select().from(agentAccounts).all()).toEqual([]);
  await draft.locator('xpath=ancestor::form').getByRole('button',{name:'Send',exact:true}).click();
  await expect.poll(()=>new URL(a.url()).pathname).toMatch(/^\/p\/comms-preview\/thread\//);
  await expect.poll(()=>a.getByText('Please propose setting the GitHub accounts for art to ART-BOT.',{exact:true}).count()).toBe(1);
  expect(db.select().from(agentAccounts).all()).toEqual([]);
  await a.goto(app.url+'/p/setup-preview');
  await a.locator('.loom-desk-boot').waitFor({state:'hidden'});
  const mint=a.getByRole('form',{name:'Create token',exact:true});await mint.getByRole('textbox',{name:'Token label',exact:true}).fill('Fictional owner token');const refused=a.waitForResponse(response=>new URL(response.url()).pathname==='/api/signin/token');
  await mint.getByRole('button',{name:'Create token',exact:true}).click();
  expect((await refused).status()).toBe(403);
  await expect.poll(()=>a.getByText('Sign in again to make a token.',{exact:false}).count()).toBe(1);
  expect(await a.getByLabel('Token value',{exact:true}).count()).toBe(0);
  expect(db.select().from(tokens).all().some(token=>token.label==='Fictional owner token')).toBe(false);
  await a.getByRole('heading',{name:'Kitchen tablet',exact:true}).locator('..').getByRole('button',{name:'Sign out browser',exact:true}).click();await expect.poll(()=>b.getByRole('heading',{name:'Kitchen tablet',exact:true}).count()).toBe(0);
  const shots=resolve('artifacts/household-setup');mkdirSync(shots,{recursive:true});await a.screenshot({path:join(shots,'setup-shared.png'),animations:'disabled'});expect(errors).toEqual([]);expect(legacy).toBe(0);
 }finally{await browser.close();await app.close();memory.close();client.close();}
});
