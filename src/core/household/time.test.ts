import { afterEach, expect, it } from 'vitest';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { WebSocket } from 'ws';
import { startLoom } from '../../foundation.js';
import { fixture, installFixture } from '../../fixture.js';
import { FakeClock } from '../clock.js';
import { HouseholdDatabase } from './document.js';
const stops:(()=>Promise<void>)[]=[];
afterEach(async()=>{for(const stop of stops.splice(0).reverse())await stop();});
it('publishes only the signed-in member minute, advances on server boundaries and rereads the database zone',async()=>{
 const home=mkdtempSync(join(tmpdir(),'household-time-'));fixture(home);
 stops.push(async()=>rmSync(home,{recursive:true,force:true}));
 const clock=new FakeClock(Date.parse('2026-11-13T18:41:59Z'));
 const app=await startLoom({home,next:true,clock,install:installFixture,authenticate:()=>({viewer:{kind:'member',id:'pollock'},valid:()=>true})});stops.push(()=>app.close());
 const household=new HouseholdDatabase(app.db);household.change(home,raw=>{raw.tz='America/Chicago';});
 const ws=new WebSocket(app.url.replace('http:','ws:')+'/live');
 const queue:unknown[]=[];let resolve:((v:unknown)=>void)|undefined;
 ws.on('message',data=>{const value=JSON.parse(data.toString());if(resolve){const r=resolve;resolve=undefined;r(value);}else queue.push(value);});
 const next=()=>queue.length?Promise.resolve(queue.shift()):new Promise(r=>{resolve=r;});
 await once(ws,'open');stops.push(async()=>{if(ws.readyState===WebSocket.CLOSED)return;const closed=once(ws,'close');ws.close();await closed;});
 ws.send(JSON.stringify({kind:'subscribe',type:'household.time'}));
 expect(await next()).toEqual({kind:'set',type:'household.time',records:[{id:'pollock',member:'pollock',at:clock.now(),timezone:'America/Chicago'}]});
 clock.advance(1000);
 expect(await next()).toMatchObject({kind:'put',record:{at:Date.parse('2026-11-13T18:42:00Z'),timezone:'America/Chicago'}});
 household.change(home,raw=>{raw.tz='Asia/Tokyo';});clock.advance(60_000);
 expect(await next()).toMatchObject({kind:'put',record:{timezone:'Asia/Tokyo'}});
 household.change(home,raw=>{raw.members=(raw.members as {person:string}[]).filter(m=>m.person!=='pollock');});
 app.live.refreshAccess();expect(await next()).toMatchObject({kind:'set',records:[]});
});
